    private static AccountCategory GetCategory(string code)
    {
        if (string.IsNullOrEmpty(code)) return AccountCategory.Asset;
        return code[0] switch
        {
            '1' => AccountCategory.Asset,
            '2' => AccountCategory.Liability,
            '3' => AccountCategory.Expense,
            '4' => AccountCategory.Revenue,
            _ => AccountCategory.Asset
        };
    }

