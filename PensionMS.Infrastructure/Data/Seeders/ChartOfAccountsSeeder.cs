    public static async Task SeedAsync(PensionDbContext context)
    {
        if (await context.ChartOfAccounts.AnyAsync()) return;

        var data = GetAllAccounts();
        var codeToId = new Dictionary<string, int>();

        foreach (var (code, name, nature, level, bookNumber, isPostable, parentCode) in data)
        {
            int? parentId = null;
            if (!string.IsNullOrEmpty(parentCode) && codeToId.TryGetValue(parentCode, out var pid))
                parentId = pid;

            var account = new ChartOfAccount
            {
                AccountCode = code,
                AccountName = name,
                AccountNature = nature,
                AccountLevel = level,
                ParentAccountID = parentId,
                BookNumber = bookNumber,
                IsPostable = isPostable,
                AccountCategory = GetCategory(code),
                IsActive = code.StartsWith("4") ? ActiveRevenueAccountCodes.Contains(code) : !InactiveUsageAccountCodes.Contains(code),
                CreatedAt = DateTime.UtcNow
            };

            context.ChartOfAccounts.Add(account);
            await context.SaveChangesAsync();
            codeToId[code] = account.AccountID;
        }
    }

